"""Match metadata, teams and players.

All clubs, players, venues and competitions in PitchLens are fictional and
generated by :mod:`pitchlens.synth`. Coordinates use a 105 x 68 m pitch with
the origin at the bottom-left corner flag (x along the length, y across).
"""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel, Field

PITCH_LENGTH = 105.0
PITCH_WIDTH = 68.0


class Position(StrEnum):
    GK = "GK"
    RB = "RB"
    CB = "CB"
    LB = "LB"
    DM = "DM"
    CM = "CM"
    AM = "AM"
    RW = "RW"
    LW = "LW"
    ST = "ST"


class PlayerAttributes(BaseModel):
    """Fictional attributes (0..1) that drive simulated behaviour."""

    passing: float = Field(0.6, ge=0, le=1)
    vision: float = Field(0.5, ge=0, le=1)
    pressing: float = Field(0.5, ge=0, le=1)
    tackling: float = Field(0.5, ge=0, le=1)
    pace: float = Field(0.5, ge=0, le=1)
    stamina: float = Field(0.6, ge=0, le=1)
    finishing: float = Field(0.4, ge=0, le=1)
    dribbling: float = Field(0.5, ge=0, le=1)


class Player(BaseModel):
    id: str
    team_id: str
    name: str
    short_name: str
    number: int = Field(ge=1, le=99)
    position: Position
    role: str = Field(description="Tactical role, e.g. 'pressing playmaker'")
    starter: bool = True
    attributes: PlayerAttributes = PlayerAttributes()
    skin_tone: int = Field(0, ge=0, le=5, description="Index into the illustration palette")


class Kit(BaseModel):
    shirt: str = Field(description="Hex colour")
    shorts: str
    socks: str
    number: str = "#ffffff"
    gk_shirt: str = "#2bd96b"


class Team(BaseModel):
    id: str
    name: str
    short: str = Field(min_length=3, max_length=3)
    city: str
    formation: str = "4-3-3"
    kit: Kit
    primary: str
    secondary: str
    style: str = Field("balanced", description="Coaching style flavour used by the generator")
    players: list[Player]

    def player(self, player_id: str) -> Player:
        for p in self.players:
            if p.id == player_id:
                return p
        raise KeyError(player_id)


class MatchMeta(BaseModel):
    match_id: str
    competition: str = "Synthetic Premier Showcase"
    venue: str
    kickoff_utc: str
    seed: int
    narrative: str
    duration_s: float = Field(description="Simulated length in seconds of match clock")
    home: Team
    away: Team
    synthetic: bool = True
    generator_version: str = "1.0"

    def team(self, team_id: str) -> Team:
        if team_id == self.home.id:
            return self.home
        if team_id == self.away.id:
            return self.away
        raise KeyError(team_id)

    def all_players(self) -> list[Player]:
        return [*self.home.players, *self.away.players]

    def player(self, player_id: str) -> Player:
        for p in self.all_players():
            if p.id == player_id:
                return p
        raise KeyError(player_id)
